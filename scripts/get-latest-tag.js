import { execSync } from 'child_process';
import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const outPath = join(root, 'git-info.generated.ts');

let tag = '';
try {
  tag = execSync('git describe --tags --abbrev=0', { encoding: 'utf-8', cwd: root }).trim();
} catch {
  // no tags or not a git repo
}

const content = `// Generated by scripts/get-latest-tag.js - do not edit manually
export const latestGitTag = ${tag ? `'${tag}'` : "''"};
`;

writeFileSync(outPath, content, 'utf-8');
